-- Tabelas do DenuncieJá no Postgres (Supabase).
-- A API roda este arquivo sozinha ao subir; também dá para colar no SQL Editor do Supabase.
-- Pode rodar quantas vezes quiser: só cria o que ainda não existe.
-- As datas ficam em texto ISO (2026-11-23T14:02:00.000Z), igual na versão SQLite.

CREATE TABLE IF NOT EXISTS usuarios (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  senha_hash TEXT NOT NULL,
  papel TEXT NOT NULL DEFAULT 'cidadao' CHECK (papel IN ('cidadao', 'admin')),
  pontos INTEGER NOT NULL DEFAULT 0,
  bloqueado INTEGER NOT NULL DEFAULT 0,
  criado_em TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
  ultimo_acesso TEXT
);

CREATE TABLE IF NOT EXISTS denuncias (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  protocolo TEXT NOT NULL UNIQUE,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
  tipo TEXT NOT NULL CHECK (tipo IN ('SITE', 'REDE_SOCIAL')),
  plataforma TEXT,
  perfil TEXT,
  categoria TEXT NOT NULL,
  titulo TEXT NOT NULL,
  url TEXT NOT NULL,
  url_normalizada TEXT NOT NULL,
  descricao TEXT NOT NULL,
  score INTEGER NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'PENDENTE'
    CHECK (status IN ('PENDENTE', 'EM_ANALISE', 'CONFIRMADA', 'REJEITADA')),
  criada_em TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
  atualizada_em TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
);

CREATE INDEX IF NOT EXISTS idx_denuncias_usuario ON denuncias (usuario_id, criada_em);
CREATE INDEX IF NOT EXISTS idx_denuncias_status ON denuncias (status);
CREATE INDEX IF NOT EXISTS idx_denuncias_url ON denuncias (url_normalizada);

-- arquivo = caminho do print no bucket "evidencias" do Storage (ou na pasta uploads/ sem Supabase)
CREATE TABLE IF NOT EXISTS evidencias (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  denuncia_id INTEGER NOT NULL REFERENCES denuncias(id) ON DELETE CASCADE,
  arquivo TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS historico_status (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  denuncia_id INTEGER NOT NULL REFERENCES denuncias(id) ON DELETE CASCADE,
  status TEXT NOT NULL,
  nota TEXT,
  motivo TEXT,
  variacao_pontos INTEGER NOT NULL DEFAULT 0,
  criado_em TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
);

CREATE TABLE IF NOT EXISTS codigos_recuperacao (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  codigo_hash TEXT NOT NULL,
  expira_em BIGINT NOT NULL,
  tentativas INTEGER NOT NULL DEFAULT 0,
  usado INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS avisos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  tipo TEXT NOT NULL CHECK (tipo IN ('STATUS', 'NIVEL')),
  denuncia_id INTEGER REFERENCES denuncias(id) ON DELETE CASCADE,
  titulo TEXT NOT NULL,
  texto TEXT NOT NULL,
  lido INTEGER NOT NULL DEFAULT 0,
  criado_em TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
);

CREATE INDEX IF NOT EXISTS idx_avisos_usuario ON avisos (usuario_id, lido, criado_em);

-- RLS ligado e nenhuma regra de acesso: a API automática do Supabase (Data API) não lê nem grava nada.
-- Só a nossa API mexe nos dados, conectando direto no Postgres como dona das tabelas.
ALTER TABLE usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE denuncias ENABLE ROW LEVEL SECURITY;
ALTER TABLE evidencias ENABLE ROW LEVEL SECURITY;
ALTER TABLE historico_status ENABLE ROW LEVEL SECURITY;
ALTER TABLE codigos_recuperacao ENABLE ROW LEVEL SECURITY;
ALTER TABLE avisos ENABLE ROW LEVEL SECURITY;
